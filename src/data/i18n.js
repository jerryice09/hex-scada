// key에 해당하는 번역을 반환. locale에 없으면 한국어(ko) → key 순으로 대체(fallback)한다.
// params가 있으면 "{n}", "{time}", "{status}" 같은 자리표시자를 치환한다.
export function translate(locale, key, params) {
  let str = STRINGS[locale]?.[key] ?? STRINGS.ko[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
  }
  return str;
}
